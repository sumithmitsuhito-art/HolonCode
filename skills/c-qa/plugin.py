@tool
def c_knowledge_search(query: str, module_id: str = "", top_k: int = 5):
    """【C语言知识库搜索工具】从本地C语言27个知识点模块知识库中检索相关内容。

    在角色互换答疑模式中，你必须先用此工具搜索当前模块的知识点。

    参数：
        query:     搜索关键词
        module_id: 当前选中的模块编号(0-26)
        top_k:     返回条数，默认5条
    """
    from atri.rag import search_knowledge_to_text
    mid = module_id if module_id != "" else None
    return search_knowledge_to_text(query, module_id=mid, top_k=top_k)


@tool
def c_qa_get_questions(module_id: str):
    """【角色互换答疑专用工具】获取指定模块的标准化知识点问题列表。

    强制要求：在角色互换模式下，你必须使用此工具获取问题，
    而不是自己编造问题！这样可以确保问题的质量和针对性。

    用法：调用此工具获取问题列表，然后逐个向用户提问。

    参数：
        module_id: 模块编号(0-26)，对应27个C语言知识点模块
    """
    if module_id not in MODULE_QUESTIONS:
        return f"错误：模块 {module_id} 不存在。有效模块编号为 0-26。"

    module_name = TOPIC_NAMES.get(module_id, f"模块{module_id}")
    questions = MODULE_QUESTIONS[module_id]

    lines = [
        f"【{module_name}】标准化知识点问题列表",
        f"共 {len(questions)} 个问题，请按顺序逐个提问：",
        "",
    ]
    for i, q in enumerate(questions, 1):
        lines.append(f"{i}. {q}")

    lines.extend([
        "",
        "使用说明：",
        "- 按顺序每次只问一个问题",
        "- 用户回答后，确认理解再问下一个",
        "- 所有问题问完后，请求用户总结该模块知识点",
    ])

    return "\n".join(lines)


@tool
def c_knowledge_list_modules():
    """列出C语言知识库中已有的所有知识点模块（编号、名称）。"""
    from atri.rag import list_kb_modules
    mods = list_kb_modules()
    if not mods:
        return "知识库当前为空，正在初始化默认模块内容..."
    lines = ["C语言知识库共有 {} 个模块：".format(len(mods))]
    for m in mods:
        lines.append("  模块 {}：{}".format(m.get("id", "?"), m.get("name", "?")))
    return "\n".join(lines)
